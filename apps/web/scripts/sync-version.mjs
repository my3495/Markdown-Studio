/**
 * 把发布版本号同步到源码常量。
 *
 * 唯一真相源是 `apps/desktop/src-tauri/tauri.conf.json` 的 `version`（发版只改这里）。
 * 生成 `src/platform/version.generated.ts` 而不是走 Vite define/插件，原因：
 *
 * - Vite 的 `define` 插件在 dev 直接 return（只在 build 替换），`pnpm dev` 下常量
 *   永远是 undefined，网页端「关于与更新」继续显示 0.0.0；
 * - 改 vite.config 又会触发依赖重优化（清空 `node_modules/.vite/deps`），在受管控的
 *   终端里容易被 safe-delete 拦下，dev server 起不来。
 *
 * 生成值是否正确由单测兜底（`src/platform/__tests__/version.test.ts` 会比对 tauri.conf）。
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { dirname, relative, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url)); // apps/web/scripts
const repoRoot = resolve(here, '../../..');
const confPath = resolve(repoRoot, 'apps/desktop/src-tauri/tauri.conf.json');
const outPath = resolve(repoRoot, 'apps/web/src/platform/version.generated.ts');

let version;
try {
  version = JSON.parse(readFileSync(confPath, 'utf8')).version;
} catch (e) {
  console.error(`[sync-version] 读取 ${confPath} 失败：${e.message}`);
  process.exit(1);
}
if (!/^\d+\.\d+\.\d+/.test(String(version ?? ''))) {
  console.error(`[sync-version] tauri.conf.json 里的 version 非法：${version}`);
  process.exit(1);
}

// 生成内容保持纯 ASCII：跨工具/跨编码读取时不会出现乱码
const content = `/* Auto-generated by apps/web/scripts/sync-version.mjs. Do not edit. */
export const APP_VERSION = '${version}';
`;

const prev = existsSync(outPath) ? readFileSync(outPath, 'utf8') : '';
if (prev !== content) writeFileSync(outPath, content, 'utf8');
console.log(`[sync-version] v${version} → ${relative(repoRoot, outPath)}`);
